/**
 * Merge a partial config (from Remote Config or storage) over the defaults.
 * Anything missing or malformed falls back to the default for that key, so a
 * bad remote value can never leave the extension without a working config.
 */
export function mergeConfig(partial: unknown): TripwireConfig {
  if (!partial || typeof partial !== 'object') return DEFAULT_CONFIG;
  const p = partial as Record<string, unknown>;
  const candidate = {
    ...DEFAULT_CONFIG,
    ...p,
    thresholds: { ...DEFAULT_CONFIG.thresholds, ...(p.thresholds as object | undefined) },
    keywords: { ...DEFAULT_CONFIG.keywords, ...(p.keywords as object | undefined) },
  };
  const parsed = TripwireConfigSchema.safeParse(candidate);
  if (!parsed.success) return DEFAULT_CONFIG;
  // Thresholds must stay ordered or the middle band disappears.
  if (parsed.data.thresholds.low >= parsed.data.thresholds.high) {
    return { ...parsed.data, thresholds: DEFAULT_CONFIG.thresholds };
  }
  return parsed.data;
}
