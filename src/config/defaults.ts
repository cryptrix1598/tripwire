export const ThresholdsSchema = z.object({
  /** Below this, the page is treated as safe and Tripwire stays invisible. */
  low: z.number().min(0).max(100),
  /** At or above this, the on-device verdict alone is enough to trip. */
  high: z.number().min(0).max(100),
  /** Minimum model confidence for a local-only trip. */
  minTripConfidence: z.number().min(0).max(1),
  /** Minimum deterministic rule score that must corroborate a local-only trip. */
  minCorroboration: z.number().min(0).max(100),
  /** Rule score needed for a caution when no AI model could be reached at all. */
  rulesOnlyCaution: z.number().min(0).max(100),
});
export type Thresholds = z.infer<typeof ThresholdsSchema>;

export const KeywordListsSchema = z.record(z.string(), z.array(z.string()));

export const TripwireConfigSchema = z.object({
  thresholds: ThresholdsSchema,
  promptVersion: z.string().min(1),
  cloudModel: z.string().min(1),
  /** Hard cap on characters of page text handed to any model. */
  maxScanChars: z.number().int().min(500).max(12000),
  /** Cap on the excerpt any model actually reads. Long pages are cut down to the sentences that carry the ask. */
  maxModelChars: z.number().int().min(400).max(6000),
  /** How long a flagged page keeps risky downloads "armed", in minutes. */
  flaggedPageMemoryMinutes: z.number().min(1).max(120),
  keywords: KeywordListsSchema,
  /** Phrases that show a page is warning ABOUT scams rather than running one. */
  protectivePhrases: z.array(z.string()),
  /** File-name fragments of remote-access tools scammers ask victims to install. */
  remoteAccessTools: z.array(z.string()),
});
export type TripwireConfig = z.infer<typeof TripwireConfigSchema>;

